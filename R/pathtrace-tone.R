pathtrace_tone_3d <- function(colour, exposure, tone) {
  x <- pmax(colour, 0) * 2^exposure
  if (tone == "clip") return(pmin(x, 1))
  if (tone == "aces") {
    x <- pmin(x, 1e10)
    return(pmin(pmax(x * (2.51 * x + 0.03) / (x * (2.43 * x + 0.59) + 0.14), 0), 1))
  }
  to2020 <- matrix(c(.6274, .3293, .0433, .0691, .9195, .0113, .0164, .0880, .8956), 3L, byrow = TRUE)
  to709 <- matrix(c(1.6605, -.5876, -.0728, -.1246, 1.1329, -.0083, -.0182, -.1006, 1.1187), 3L, byrow = TRUE)
  inset <- matrix(c(.856627153315983, .0951212405381588, .0482516061458583,
    .137318972929847, .761241990602591, .101439036467562,
    .11189821299995, .0767994186031903, .811302368396859), 3L, byrow = TRUE)
  outset <- matrix(c(1.1271005818144368, -.11060664309660323, -.016493938717834573,
    -.1413297634984383, 1.157823702216272, -.016493938717834257,
    -.14132976349843826, -.11060664309660294, 1.2519364065950405), 3L, byrow = TRUE)
  x <- pmin(x, 1e30) %*% t(inset %*% to2020)
  x <- pmin(pmax((log2(pmax(x, 1e-10)) + 12.47393) / 16.499999, 0), 1)
  x <- 15.5 * x^6 - 40.14 * x^5 + 31.96 * x^4 - 6.868 * x^3 + .4298 * x^2 + .1191 * x - .00232
  pmin(pmax(pmax(x %*% t(outset), 0)^2.2 %*% t(to709), 0), 1)
}
